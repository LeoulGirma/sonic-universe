"""Build src/audio/libraryRef.ts: quantile tables of song-profile features over a music library.
   python3 scripts/build-library-ref.py profiles.jsonl [more.jsonl ...]
The app places a new song by interpolating each feature into these tables (a percentile within
the library), combining them with the weights in songMood.ts, then mapping the composite through
its own table so energy and brightness spread evenly over 0..1."""
import json, sys, math
import numpy as np

rows = []
for f in sys.argv[1:]:
    for l in open(f):
        d = json.loads(l)
        if d.get('profile'): rows.append(d['profile'])
seen = set()

def feats(p):
    s = p['share']
    f = {
        'loud': p['loud'], 'dyn': p['dyn'], 'cent': math.log(max(p['centroid'], 1)), 'bpm': p['bpm'], 'pulse': p['pulse'],
        'kick': p['kickRate'], 'ons': p['onsetRate'], 'notes': p['noteRate'], 'mode': p['mode'], 'keyc': p['keyClarity'],
        'mel': p['melody'], 'chord': p['chordRate'], 'drops': p['drops'], 'brk': p['breakdown'],
        'low': s[0] + s[3], 'perc': s[0] + s[1] + s[2], 'lead': s[5], 'pads': s[4],
    }
    for k in ('third', 'flat', 'hiShare'):
        if k in p: f[k] = p[k]
    return f

F = [feats(p) for p in rows]
keys = [k for k in F[0] if all(k in f for f in F)]
Q = np.linspace(0, 1, 21)
tables = {k: np.quantile([f[k] for f in F], Q).tolist() for k in keys}

def pct(k, v):
    t = tables[k]
    return float(np.interp(v, t, Q)) if t[-1] > t[0] else 0.5

# weights must match songMood.ts
EW = {'loud': 1.5, 'ons': 1.5, 'kick': 1, 'cent': 1, 'notes': 1, 'dyn': -0.7, 'bpm': 0.5}
if 'flat' in tables: EW['flat'] = 0.5
BW = {'mode': 2.5, 'cent': 1, 'bpm': 0.7, 'keyc': 0.5, 'chord': 0.6}
if 'third' in tables: BW = {'mode': 2.5, 'third': 0.5, 'cent': 0.8, 'bpm': 0.4, 'chord': 0.4}
def comp(f, W):
    s = sum((pct(k, f[k]) if w > 0 else 1 - pct(k, f[k])) * abs(w) for k, w in W.items())
    return s / sum(abs(w) for w in W.values())
tables['_energy'] = np.quantile([comp(f, EW) for f in F], Q).tolist()
tables['_bright'] = np.quantile([comp(f, BW) for f in F], Q).tolist()

out = '/** Generated by scripts/build-library-ref.py from %d songs: 21-point quantile tables per feature. */\n' % len(F)
out += 'export const LIB_SONGS = %d;\n' % len(F)
out += 'export const ENERGY_W: Record<string, number> = %s;\n' % json.dumps(EW)
out += 'export const BRIGHT_W: Record<string, number> = %s;\n' % json.dumps(BW)
out += 'export const LIB: Record<string, number[]> = {\n' + ''.join('  %s: [%s],\n' % (k if k.isidentifier() else json.dumps(k), ', '.join('%.5g' % x for x in v)) for k, v in tables.items()) + '};\n'
open('src/audio/libraryRef.ts', 'w').write(out)
print(len(F), 'songs;', len(tables), 'tables; brightness weights', BW)
